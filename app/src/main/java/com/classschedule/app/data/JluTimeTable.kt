package com.classschedule.app.data

/**
 * 吉林大学作息时间表（节次 -> 上下课时间），时间由用户按校区实际作息核对提供。
 *
 * 结构：上午 4 节 + 下午 4 节 + 晚上 4 节，共 12 节。
 * - 课间一般为 10 分钟；第 2~3 节之间为大课间 20 分钟（09:40 -> 10:00）。
 * - 晚上为两节连堂：9~10 节、11~12 节之间仅 1 分钟间隔，
 *   两大堂之间休息 10 分钟（19:50 -> 20:00）。
 *
 * 如果与你所在校区 / 年级的实际作息不符，直接修改下方 [PERIODS] 即可，
 * 周视图会自动按新的节次数与时间渲染。
 */
object JluTimeTable {

    /** 一个节次：序号、上课时间、下课时间。 */
    data class Period(val index: Int, val start: String, val end: String)

    val PERIODS: List<Period> = listOf(
        // 上午（大课间 20 分钟在第 2~3 节之间）
        Period(1, "08:00", "08:45"),
        Period(2, "08:55", "09:40"),
        Period(3, "10:00", "10:45"),
        Period(4, "10:55", "11:40"),
        // 下午
        Period(5, "13:30", "14:15"),
        Period(6, "14:25", "15:10"),
        Period(7, "15:30", "16:15"),
        Period(8, "16:25", "17:10"),
        // 晚上（9~10、11~12 节连堂，中间 19:50~20:00 休息）
        Period(9, "18:30", "19:05"),
        Period(10, "19:06", "19:50"),
        Period(11, "20:00", "20:45"),
        Period(12, "20:46", "21:30"),
    )

    /** 学期总周数（吉林大学本科一般 16~18 周，考试周另计）。 */
    const val TOTAL_WEEKS: Int = 16
}
